import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const source = await readFile("app/page.tsx", "utf8");
const seasons = [...source.matchAll(/\[(\d{4}),"([^"]+)","[^"]+"\]/g)].map((m) => ({ year: Number(m[1]), name: m[2] }));
const outDir = "public/seasons";
await mkdir(outDir, { recursive: true });

const badWords = /\b(car|model|replica|statue|memorial|grave|autograph|signature|museum|helmet only)\b/i;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const slug = (value) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

async function fetchWithBackoff(url) {
  for (let attempt = 0; attempt < 7; attempt++) {
    const response = await fetch(url, { headers: { "User-Agent": "F1ChampionsHistoryPrototype/1.0 (local design research)" } });
    if (response.status !== 429) return response;
    const wait = Math.min(30000, 5000 * (attempt + 1));
    console.log(`Rate limited; waiting ${wait / 1000}s…`);
    await sleep(wait);
  }
  throw new Error("Rate limit did not clear");
}

async function findImage({ year, name }) {
  const params = new URLSearchParams({
    action: "query", generator: "search", gsrsearch: `${name} ${year} Formula One`,
    gsrnamespace: "6", gsrlimit: "10", prop: "imageinfo", iiprop: "url|size|mime",
    iiurlwidth: "1600", format: "json", origin: "*",
  });
  const response = await fetchWithBackoff(`https://commons.wikimedia.org/w/api.php?${params}`);
  if (!response.ok) throw new Error(`Search failed: ${response.status}`);
  const json = await response.json();
  const surname = slug(name.split(" ").at(-1));
  const candidates = Object.values(json.query?.pages || {}).map((page) => {
    const info = page.imageinfo?.[0];
    const title = slug(page.title || "");
    let score = 0;
    if (title.includes(surname)) score += 12;
    if (title.includes(String(year))) score += 10;
    if (/portrait|podium|champion|grand-prix|formula-one|f1/.test(title)) score += 2;
    if (badWords.test(page.title || "")) score -= 8;
    if ((info?.width || 0) >= 900 && (info?.height || 0) >= 600) score += 2;
    score -= (page.index || 10) * .1;
    return { page, info, score };
  }).filter((x) => x.info?.thumburl && /image\/(jpeg|png|webp)/.test(x.info.mime || "")).sort((a,b) => b.score - a.score);
  return candidates[0];
}

async function processSeason(season) {
  const existing = resultsByYear.get(season.year);
  if (existing?.file) return existing;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const found = await findImage(season);
      if (!found || found.score < 8) return { ...season, fallback: true };
      return { ...season, file: found.info.thumburl, source: found.info.descriptionurl, title: found.page.title, score: found.score };
    } catch (error) {
      if (attempt === 2) return { ...season, fallback: true, error: String(error) };
      await sleep(700 * (attempt + 1));
    }
  }
}

let previous = [];
try { previous = JSON.parse(await readFile("SEASON_IMAGE_SOURCES.json", "utf8")); } catch {}
const resultsByYear = new Map(previous.map((item) => [item.year, item]));
const results = [];
for (let i = 0; i < seasons.length; i++) {
  results.push(await processSeason(seasons[i]));
  console.log(`Fetched ${i + 1} / ${seasons.length}`);
  await sleep(2500);
}

const mapping = Object.fromEntries(results.filter((x) => x.file).map((x) => [x.year, x.file]));
await writeFile("app/season-images.generated.ts", `// Generated by scripts/fetch-season-images.mjs\nexport const seasonImages: Record<number, string> = ${JSON.stringify(mapping, null, 2)};\n`);
await writeFile("SEASON_IMAGE_SOURCES.json", JSON.stringify(results, null, 2));
console.log(`Complete: ${Object.keys(mapping).length} year-specific images, ${results.filter((x) => x.fallback).length} fallbacks.`);
