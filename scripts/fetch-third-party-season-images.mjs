import { readFile, mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";

const source = await readFile("app/page.tsx", "utf8");
const seasons = [...source.matchAll(/\[(\d{4}),"([^"]+)","[^"]+"\]/g)].map((m) => ({ year:Number(m[1]), name:m[2] }));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const slug = (v) => v.normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase().replace(/[^a-z0-9]+/g,"-").replace(/(^-|-$)/g,"");
const usedImages = new Set();
const blocked = /(alamy|pinterest|gettyimages|ebay|amazon|topps|tradingcard|wallpapercave|wallpapers\.com)/i;
const outDir = "public/seasons-unique";
await mkdir(outDir,{recursive:true});

async function fetchTimeout(url, options={}, timeout=14000){
  return fetch(url,{...options,signal:AbortSignal.timeout(timeout)});
}

async function searchImages(query){
  for(let attempt=0;attempt<5;attempt++){
    try{
      const html=await (await fetchTimeout(`https://duckduckgo.com/?q=${encodeURIComponent(query)}`,{headers:{"User-Agent":"Mozilla/5.0"}})).text();
      const vqd=html.match(/vqd=([\d-]+)/)?.[1];
      if(!vqd)throw new Error("missing token");
      const url=`https://duckduckgo.com/i.js?l=us-en&o=json&q=${encodeURIComponent(query)}&vqd=${vqd}&f=,,,&p=1`;
      const response=await fetchTimeout(url,{headers:{"User-Agent":"Mozilla/5.0","Referer":"https://duckduckgo.com/"}});
      if(!response.ok)throw new Error(`search ${response.status}`);
      return (await response.json()).results||[];
    }catch(error){if(attempt===4)throw error;await sleep(4000*(attempt+1));}
  }
}

async function chooseAndSave(season, results){
  const good=results.filter(x=>x.image&&!usedImages.has(x.image)&&!blocked.test(`${x.image} ${x.url}`)&&(x.width||0)>=700&&(x.height||0)>=500);
  for(const candidate of good.slice(0,30)){
    try{
      const response=await fetchTimeout(candidate.image,{headers:{"User-Agent":"Mozilla/5.0","Referer":candidate.url||"https://duckduckgo.com/"}});
      if(!response.ok)continue;
      const type=response.headers.get("content-type")||"";
      if(!type.startsWith("image/"))continue;
      const bytes=Buffer.from(await response.arrayBuffer());
      if(bytes.length<30000)continue;
      const filename=`${season.year}-${slug(season.name)}.webp`;
      await sharp(bytes).rotate().resize(1200,1200,{fit:"cover",position:sharp.strategy.attention}).webp({quality:85}).toFile(`${outDir}/${filename}`);
      usedImages.add(candidate.image);
      return {year:season.year,name:season.name,file:`/seasons-unique/${filename}`,source:candidate.url,imageSource:candidate.image,title:candidate.title};
    }catch{}
  }
  return null;
}

const audit=[];
for(let i=0;i<seasons.length;i++){
  const season=seasons[i];
  const query=`${season.name} ${season.year} Formula 1 podium portrait`;
  const results=await searchImages(query);
  const saved=await chooseAndSave(season,results);
  if(!saved)throw new Error(`No usable unique image for ${season.year} ${season.name}`);
  audit.push(saved);
  console.log(`${i+1}/${seasons.length} ${season.year} ${saved.title}`);
  await sleep(1300);
}

const mapping=Object.fromEntries(audit.map(x=>[x.year,x.file]));
if(new Set(audit.map(x=>x.imageSource)).size!==seasons.length)throw new Error("Duplicate source image detected");
await writeFile("app/season-images.generated.ts",`// Generated by scripts/fetch-third-party-season-images.mjs\nexport const seasonImages: Record<number,string> = ${JSON.stringify(mapping,null,2)};\n`);
await writeFile("THIRD_PARTY_IMAGE_AUDIT.json",JSON.stringify(audit,null,2));
console.log(`Complete: ${audit.length} unique images; duplicate count 0.`);
