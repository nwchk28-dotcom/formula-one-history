import { readFile, mkdir, writeFile, access } from "node:fs/promises";
import sharp from "sharp";

const results = JSON.parse(await readFile("SEASON_IMAGE_SOURCES.json", "utf8"));
const outDir = "public/seasons-ready";
await mkdir(outDir, { recursive: true });
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const slug = (value) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const unsuitable = /(integralhelm|halbschale|jethelm|helmet|stamp|museum|private collection|cars?\b|on screen|trophy)/i;
// Human-reviewed contact sheet: only these year-search results clearly show the champion.
const verifiedYearPhotos = new Set([2023, 2019, 1975, 1965, 1962]);

async function fetchWithBackoff(url) {
  for (let attempt = 0; attempt < 2; attempt++) {
    let response;
    try {
      response = await fetch(url, { headers: { "User-Agent": "F1ChampionsHistoryPrototype/1.0 (local design research)" }, signal: AbortSignal.timeout(15000) });
    } catch {
      await sleep(2500);
      continue;
    }
    if (response.ok) return Buffer.from(await response.arrayBuffer());
    if (response.status !== 429) throw new Error(`HTTP ${response.status}`);
    await sleep(Math.min(30000, 5000 * (attempt + 1)));
  }
  throw new Error("Rate limit did not clear");
}

const mapping = {};
const audit = [];
for (let i = 0; i < results.length; i++) {
  const item = results[i];
  let useSpecific = Boolean(item.file && !item.fallback && !unsuitable.test(item.title || "") && verifiedYearPhotos.has(item.year));
  const filename = `${item.year}-${slug(item.name)}.webp`;
  try {
    await access(`${outDir}/${filename}`);
    if (!useSpecific) throw new Error("Replace unverified crop");
    mapping[item.year] = `/seasons-ready/${filename}`;
    audit.push({ year: item.year, name: item.name, yearSpecific: useSpecific, source: useSpecific ? item.source : "https://www.formula1.com/en/drivers/hall-of-fame" });
    console.log(`Prepared ${i + 1} / ${results.length}: ${item.year} cached`);
    continue;
  } catch {}
  let input;
  if (useSpecific) {
    try { input = item.file.startsWith("/") ? await readFile(`public${item.file}`) : await fetchWithBackoff(item.file); }
    catch { useSpecific = false; }
  }
  if (!input) input = await readFile(`public/champions/${slug(item.name)}.webp`);
  await sharp(input)
    .rotate()
    .resize(1200, 1200, { fit: "cover", position: sharp.strategy.attention })
    .webp({ quality: 84 })
    .toFile(`${outDir}/${filename}`);
  mapping[item.year] = `/seasons-ready/${filename}`;
  audit.push({ year: item.year, name: item.name, yearSpecific: useSpecific, source: useSpecific ? item.source : "https://www.formula1.com/en/drivers/hall-of-fame" });
  console.log(`Prepared ${i + 1} / ${results.length}: ${item.year}${useSpecific ? " exact" : " official portrait"}`);
  if (useSpecific && !item.file.startsWith("/")) await sleep(850);
}

await writeFile("app/season-images.generated.ts", `// Generated by scripts/prepare-season-crops.mjs\nexport const seasonImages: Record<number, string> = ${JSON.stringify(mapping, null, 2)};\n`);
await writeFile("SEASON_IMAGE_AUDIT.json", JSON.stringify(audit, null, 2));
console.log(`Complete: ${audit.filter((x) => x.yearSpecific).length} year-specific, ${audit.filter((x) => !x.yearSpecific).length} official portrait fallbacks.`);
